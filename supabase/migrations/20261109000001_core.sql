-- The Snuggly Duckling ERP — core schema
-- One rule drives the design: every quantity and dollar comes from a posted
-- transaction. On-hand lives in inventory_txns (stock is a running total kept by
-- trigger); money lives in journal_lines. Business actions post both through the
-- functions in 0002, so every screen and every user sees the same numbers.

