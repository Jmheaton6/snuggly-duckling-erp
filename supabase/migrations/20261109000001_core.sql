create index on inventory_txns (ref_type, ref_id);

create table stock (
  item_id int not null references items(id),
  location_id smallint not null references locations(id),
  qty numeric(12,3) not null default 0,
  primary key (item_id, location_id)
);

-- Costing lives here so no caller can get it wrong:
--  * outbound rows are costed at the item's current weighted average
--  * inbound rows re-average (a transfer-in at the current average leaves it unchanged)
--  * on-hand can never go negative
create function apply_inventory_txn() returns trigger
language plpgsql as $$
declare
  v_avg numeric;
  v_total numeric;
  v_here numeric;
  v_cost numeric;
begin
  select avg_cost into v_avg from items where id = new.item_id for update;
  select coalesce(sum(qty), 0) into v_total from stock where item_id = new.item_id;

  if new.qty < 0 then
    select coalesce((select qty from stock where item_id = new.item_id and location_id = new.location_id), 0)
      into v_here;
    if v_here + new.qty < 0 then
      raise exception 'Not enough % at % (on hand %, need %)',
        (select name from items where id = new.item_id),
        (select name from locations where id = new.location_id),
        v_here, -new.qty
        using errcode = 'P0001';
    end if;
    new.unit_cost := coalesce(new.unit_cost, v_avg);
  else
    v_cost := coalesce(new.unit_cost, v_avg);
    new.unit_cost := v_cost;
    if v_total + new.qty > 0 then
      update items
         set avg_cost = round(((greatest(v_total, 0) * v_avg) + (new.qty * v_cost)) / (greatest(v_total, 0) + new.qty), 4)
       where id = new.item_id;
    end if;
  end if;

  insert into stock (item_id, location_id, qty) values (new.item_id, new.location_id, new.qty)
  on conflict (item_id, location_id) do update set qty = stock.qty + excluded.qty;
  return new;
end $$;

create trigger inventory_txns_apply before insert on inventory_txns
for each row execute function apply_inventory_txn();

create table transfers (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  item_id int not null references items(id),
  from_location_id smallint not null references locations(id),
  to_location_id smallint not null references locations(id),
  qty numeric(12,3) not null check (qty > 0),
  note text,
  user_id uuid,
  check (from_location_id <> to_location_id)
);

create table adjustments (
