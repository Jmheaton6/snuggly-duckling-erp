  unit_price numeric(10,2) not null
);

create table sales (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  location_id smallint not null references locations(id),
  customer_id int references customers(id),
  sales_order_id bigint references sales_orders(id),
  subtotal numeric(12,2) not null,
  discount_total numeric(12,2) not null default 0,
  tax numeric(12,2) not null,
  total numeric(12,2) not null,
  cogs numeric(12,2) not null,
  tax_rate numeric not null,
  tender text not null default 'card' check (tender in ('cash','card','account','exchange')),
  user_id uuid
);
create index on sales (ts);
alter table sales_orders add constraint sales_orders_sale_fk foreign key (sale_id) references sales(id)
  deferrable initially deferred;   -- orders and their sales point at each other

create table sale_lines (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references sales(id) on delete cascade,
